static int write_reg(uint8_t reg, uint8_t val)
{
  return (HAL_I2C_Mem_Write(&hi2c3, GC2145_I2C_ADDR, reg, I2C_MEMADD_SIZE_8BIT,
                            &val, 1, I2C_TIMEOUT_MS) == HAL_OK) ? 0 : -1;
}

static int read_reg(uint8_t reg, uint8_t *val)
{
  return (HAL_I2C_Mem_Read(&hi2c3, GC2145_I2C_ADDR, reg, I2C_MEMADD_SIZE_8BIT,
                           val, 1, I2C_TIMEOUT_MS) == HAL_OK) ? 0 : -1;
}

int gc2145_read_id(uint16_t *id)
{
  uint8_t hi = 0, lo = 0;
  int ret = 0;

  ret |= read_reg(0xF0, &hi);
  ret |= read_reg(0xF1, &lo);
  *id = ((uint16_t)hi << 8) | lo;
  return ret;
}

int gc2145_reset(void)
{
  int ret = 0;

  /* The table starts with a soft reset (0xFE = 0xF0 three times) */
  for (int i = 0; default_regs[i][0]; i++)
  {
    ret |= write_reg(default_regs[i][0], default_regs[i][1]);
  }

  HAL_Delay(10);
  return ret;
}

int gc2145_set_format(gc2145_format_t fmt)
{
  int ret = 0;
  uint8_t reg = 0;

  ret |= write_reg(0xFE, 0x00);  // page 0
  ret |= read_reg(REG_OUTPUT_FMT, &reg);

  switch (fmt)
  {
    case GC2145_FMT_RGB565:
      ret |= write_reg(REG_OUTPUT_FMT, REG_OUTPUT_SET_FMT(reg, REG_OUTPUT_FMT_RGB565));
      break;
    case GC2145_FMT_YUV422:
      ret |= write_reg(REG_OUTPUT_FMT, REG_OUTPUT_SET_FMT(reg, REG_OUTPUT_FMT_YCBYCR));
      break;
    default:
      return -1;
  }

  return ret;
}

static int set_window(uint8_t reg, uint16_t x, uint16_t y, uint16_t w, uint16_t h)
{
  int ret = 0;

  ret |= write_reg(0xFE, 0x00);  // page 0
  ret |= write_reg(reg++, y >> 8);
  ret |= write_reg(reg++, y & 0xFF);
  ret |= write_reg(reg++, x >> 8);
  ret |= write_reg(reg++, x & 0xFF);
  ret |= write_reg(reg++, h >> 8);
  ret |= write_reg(reg++, h & 0xFF);
  ret |= write_reg(reg++, w >> 8);
  ret |= write_reg(reg++, w & 0xFF);
  return ret;
}

/* Full-FOV readout, centred, sub-sampled down to w x h (OpenMV set_framesize) */
int gc2145_set_framesize(uint16_t w, uint16_t h)
{
  int ret = 0;

  if ((w == 0) || (h == 0) || (w > ACTIVE_SENSOR_WIDTH) || (h > ACTIVE_SENSOR_HEIGHT))
  {
    return -1;
  }

  int readout_w = ACTIVE_SENSOR_WIDTH;
  int readout_h = ACTIVE_SENSOR_HEIGHT;

  int ratio = MIN(readout_w / w, readout_h / h);
  ratio = MIN(ratio, MAX_SUBSAMPLE_RATIO);
  if (!(ratio % 2))
  {
    // camera outputs messed up bayer images at even ratios for some reason...
    ratio -= 1;
  }

  int sensor_w = (w * ratio) + DUMMY_WIDTH_BUFFER;   // dummy pixels to sync
  int sensor_h = (h * ratio) + DUMMY_HEIGHT_BUFFER;  // dummy lines to sync

  int sensor_x = CLAMP(((ACTIVE_SENSOR_WIDTH - sensor_w) / 4) * 2,
                       -(DUMMY_WIDTH_BUFFER / 2), ACTIVE_SENSOR_WIDTH - sensor_w) + DUMMY_COLUMNS;
  int sensor_y = CLAMP(((ACTIVE_SENSOR_HEIGHT - sensor_h) / 4) * 2,
                       -(DUMMY_HEIGHT_BUFFER / 2), ACTIVE_SENSOR_HEIGHT - sensor_h) + DUMMY_LINES;

  /* Readout window first, then the crop window */
  ret |= set_window(0x09, sensor_x, sensor_y, sensor_w, sensor_h);
  ret |= set_window(0x91, 0, 0, w, h);

  ret |= write_reg(0x90, 0x01);                       // enable crop
  ret |= write_reg(0x99, (ratio << 4) | ratio);       // sub-sampling ratio
  ret |= write_reg(0x9A, 0x0E);                       // sub-sampling mode

  return ret;
}

/* Sensor standby: output off, PLL and analog blocks powered down (OpenMV sleep()) */
int gc2145_sleep(int enable)
{
  int ret = 0;

  ret |= write_reg(0xFE, 0x00);  // page 0
  if (enable)
  {
    ret |= write_reg(0xF2, 0x00);
    ret |= write_reg(0xF7, 0x10);
    ret |= write_reg(0xFC, 0x01);
  }
  else
  {
    ret |= write_reg(0xF2, 0x0F);
    ret |= write_reg(0xF7, 0x1D);
    ret |= write_reg(0xFC, 0x06);
  }
  return ret;
}

/*
 * Mirror/flip relative to the board's upright orientation. Written directly
 * instead of read-modify-write: the GC2145 doesn't read register 0x17 back
 * reliably (noted in Arduino's driver too).
 */
int gc2145_set_orientation(int hmirror, int vflip)
{
  #if (GC2145_ROTATE == 1)
  hmirror = !hmirror;
  vflip = !vflip;
  #endif

  uint8_t reg = REG_AMODE1_DEF;
  reg = REG_AMODE1_SET_HMIRROR(reg, hmirror);
  reg = REG_AMODE1_SET_VMIRROR(reg, vflip);

  int ret = 0;
  ret |= write_reg(0xFE, 0x00);  // page 0
  ret |= write_reg(REG_AMODE1, reg);
  return ret;
}
